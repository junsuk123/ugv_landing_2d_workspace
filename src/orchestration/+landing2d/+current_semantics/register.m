function registration = register(phase,evidence,root)
% REGISTER Freeze one phase after actual native checks, before any full run.
% This is an experiment record, not an additional user-approval requirement.
if nargin<3, root=landing2d.orchestration.projectRoot(); end
d=landing2d.current_semantics.config(root);
assert(ismember(phase,{'development','confirmation'}));
folder=fullfile(d.outputDir,phase); file=fullfile(folder,'registration.json');
assert(~isfile(file),'landing2d:CurrentSemanticsRegistered','Preserve the existing registration.');
assert(isstruct(evidence) && isfield(evidence,'passed') && evidence.passed ...
    && isfield(evidence,'smokePassed') && evidence.smokePassed ...
    && isfield(evidence,'nativeRegressionPassed') && evidence.nativeRegressionPassed ...
    && isfield(evidence,'testOnly') && evidence.testOnly, ...
    'landing2d:CurrentSemanticsNativeGate','Actual native core, archived regression, and four-arm smoke checks are required.');
assert(isequal(evidence.parameterCounts(:)',[2095,2095,2094,2100]), ...
    'landing2d:CurrentSemanticsParameters','Unexpected parameter budget.');
assert(isfield(evidence,'sources') && isfield(evidence,'configurationSha256') ...
    && strcmp(evidence.configurationSha256,landing2d.util.sha256(jsonencode(d.c))), ...
    'landing2d:CurrentSemanticsNativeGate','Native evidence must identify this exact configuration.');
landing2d.current_semantics.verifySources(root,evidence.sources);
developmentEvidence=struct();
if strcmp(phase,'development')
    seeds=d.developmentSeeds; environments=d.developmentEnvironments;
else
    seeds=d.confirmationSeeds; environments=d.confirmationEnvironments;
    prior=fullfile(d.outputDir,'development');
    assert(isfile(fullfile(prior,'completed.json')) && isfile(fullfile(prior,'results.mat')) ...
        && isfile(fullfile(prior,'manifest.json')), ...
        'landing2d:CurrentSemanticsConfirmationClosed','Complete development before confirmation.');
    registered=jsondecode(fileread(fullfile(prior,'registration.json')));
    landing2d.current_semantics.verifySources(d.root,registered.sources);
    completed=jsondecode(fileread(fullfile(prior,'completed.json')));
    manifest=jsondecode(fileread(fullfile(prior,'manifest.json')));
    assert(completed.gatePassed && manifest.gatePassed ...
        && manifest.models==4*numel(d.developmentSeeds) && manifest.episodes==16000, ...
        'landing2d:CurrentSemanticsDevelopment','Development completion evidence is inconsistent.');
    assert(any(strcmp({manifest.outputs.file},'results.mat')), ...
        'landing2d:CurrentSemanticsDevelopment','The completion manifest does not seal development results.');
    for k=1:numel(manifest.outputs)
        item=manifest.outputs(k);
        assert(strcmp(item.sha256,landing2d.bias_diagnostics.fileHash(fullfile(prior,item.file))), ...
            'landing2d:CurrentSemanticsDevelopment','Completed development output changed: %s.',item.file);
    end
    landing2d.current_semantics.restoreTraining(d,d.developmentSeeds,prior);
    result=load(fullfile(prior,'results.mat'),'decision','results');
    assert(result.decision.passed && ~result.results.isSmoke, ...
        'landing2d:CurrentSemanticsConfirmationClosed','The frozen development gate did not pass.');
    developmentEvidence=struct('resultsSha256',landing2d.bias_diagnostics.fileHash(fullfile(prior,'results.mat')), ...
        'registrationSha256',landing2d.bias_diagnostics.fileHash(fullfile(prior,'registration.json')));
end
audit=landing2d.current_semantics.auditSeeds(d,phase);
sources=landing2d.current_semantics.sourceManifest(root);
registration=struct('version',d.version,'phase',phase, ...
    'registeredAtUtc',string(datetime('now','TimeZone','UTC')), ...
    'algorithmVersion',landing2d.rl.algorithmVersion(d.c), ...
    'trainSeeds',seeds,'environmentSeeds',environments,'methods',{d.methods}, ...
    'configurationSha256',landing2d.util.sha256(jsonencode(d.c)), ...
    'evaluationProtocol',d.c.evaluation,'primaryPairs',{d.primaryPairs}, ...
    'primaryCoverage',d.primaryCoverage,'practicalRule',d.practicalRule,'guards',d.guard, ...
    'developmentRule',d.developmentRule,'parameterCounts',evidence.parameterCounts(:)', ...
    'budget',struct('candidateCount',1,'developmentTrainingSeeds',5, ...
        'confirmationTrainingSeeds',20,'methods',4,'maxUpdatesPerModel',750, ...
        'episodesPerUpdate',6,'evaluationCells',8,'episodesPerCell',100, ...
        'confirmationAttempts',1,'adaptiveSeedExtension',false), ...
    'stopRule','One candidate and one confirmation; no seed exclusion, result-based retraining, difficulty calibration or extra confirmation.', ...
    'sources',sources,'seedAudit',audit,'nativeChecks',evidence, ...
    'developmentEvidence',developmentEvidence,'trainingStarted',false);
if ~isfolder(folder), mkdir(folder); end
landing2d.current_semantics.writeJson(file,registration);
fprintf('[current semantics] registered %s, %d sources\n',phase,numel(sources));
end
