function checkSeeds(d)
% CHECKSEEDS Keep the earlier sealed experiment and all new splits separate.
assert(isequal(d.developmentSeeds,61001:61005) ...
    && isequal(d.confirmationSeeds,61101:61120), ...
    'landing2d:CurrentSemanticsSeeds','The training-seed budget is frozen.');
assert(isequal(d.developmentEnvironments,12001:12100) ...
    && isequal(d.confirmationEnvironments,12201:12300), ...
    'landing2d:CurrentSemanticsSeeds','The evaluation namespace is frozen.');
training = [d.developmentSeeds,d.confirmationSeeds];
environment = [d.developmentEnvironments,d.confirmationEnvironments,d.smokeEnvironmentSeed];
assert(numel(unique(training))==numel(training) && numel(unique(environment))==numel(environment));
assert(isempty(intersect(training,d.forbiddenTrainSeeds)) ...
    && isempty(intersect(environment,d.forbiddenEnvironmentSeeds)), ...
    'landing2d:CurrentSemanticsSealed','Earlier reserved seeds must stay sealed.');
m = d.c.experiment.manifest;
legacy = [m.trainSeeds,m.validationSeeds,m.testSeeds,m.stressSeeds];
assert(isempty(intersect(environment,legacy)) ...
    && all(environment<m.fixedCaseSeedRange(1)), ...
    'landing2d:CurrentSemanticsSeeds','New evaluation seeds overlap an existing split or case range.');
assert(~ismember(d.smokeTrainSeed,training));
assert(numel(d.methods)==4 && isequal(d.methods, ...
    {'ppo','semantic_mlp_ppo','untyped_gnn_ppo','onto_rgat_ppo'}));
end
