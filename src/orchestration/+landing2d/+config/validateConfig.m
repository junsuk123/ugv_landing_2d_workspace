function validateConfig(c)
% VALIDATECONFIG  Validate a complete configuration of the planar contract.
for name = {'padHalfLength','axMax','azMax','vxMax','vzMax'}
    validateattributes(c.(name{1}),{'numeric'},{'scalar','real','finite','positive'}, ...
        mfilename,name{1});
end
assert(ischar(c.outputDir) && ~isempty(strtrim(c.outputDir)), ...
    'outputDir must be a nonempty character vector.');
landing2d.rl.validateRlConfig(c.rl);
landing2d.graphstate.validateGraphStateConfig(c.graphState);
assert(isfield(c,'experiment') && c.experiment.enabled ...
    && strcmp(c.experiment.schemaVersion,'planar_visibility_v2'), ...
    'landing2d:ExperimentVersion','The planar_visibility_v2 experiment is required.');
e = c.experiment;
assert(e.observationSchema.dimension == numel(e.observationSchema.names) ...
    && c.rl.observationDim == e.observationSchema.dimension, ...
    'landing2d:ObservationSchema','RL dimension must come from the named schema.');
assert(c.rl.actionDim == 2,'landing2d:ActionContract', ...
    'The 2D planar experiment requires [a_x,a_z].');
landing2d.config.validatePrimaryConfig(c);
end
