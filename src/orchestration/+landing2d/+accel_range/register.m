function registration = register(report,notes)
% REGISTER Write registration.json of acceleration_range_r1_v1 before any training.
%   landing2d.accel_range.register(report,notes)
% REPORT is a passed landing2d.accel_range.checkSetup report; NOTES records
% checks run outside the package (e.g. the ppoTrain default-path regression).
% Registers the SHA-256 of every MATLAB source under src/ and of the design
% document, the v5 control episodes and checkpoints, the seeds, the evaluation
% contract and the criteria. Refuses an existing registration.
d = landing2d.accel_range.config();
file = fullfile(d.outputDir,'registration.json');
assert(~isfile(file),'landing2d:AccelRangeRegistered','Preserve the existing registration %s.',file);
if ~isfolder(d.outputDir), mkdir(d.outputDir); end
sources = dir(fullfile(d.root,'src','**','*.m'));
paths = [arrayfun(@(f)fullfile(f.folder,f.name),sources,'UniformOutput',false); ...
    {fullfile(d.root,'docs','ACCELERATION_RANGE_R1_KO.md')}];
code = cellfun(@(p)struct('path',relativePath(d.root,p), ...
    'sha256',string(landing2d.bias_diagnostics.fileHash(p))),paths);
base = landing2d.bias_diagnostics.config(d.root);
v5Runs = landing2d.bias_diagnostics.models(base,d.trainSeeds);
controls = arrayfun(@(r)struct('MethodId',string(r.id),'TrainSeed',r.trainSeed, ...
    'file',relativePath(d.root,char(r.file)),'fileSha256',r.fileSha256, ...
    'identityHash',string(r.identity.CheckpointHash)),v5Runs);
inputs = {fullfile(d.v5Evaluation,'generalizationEpisodes.csv'),fullfile(d.v5Evaluation,'runManifest.csv'), ...
    fullfile(d.root,'results','generalization_v2_calibration','protocol_registration.json')};
evidence = cellfun(@(p)struct('path',relativePath(d.root,p), ...
    'sha256',string(landing2d.bias_diagnostics.fileHash(p))),inputs);
registration = struct('version',d.version,'registeredAtUtc',string(datetime('now','TimeZone','UTC')), ...
    'approval','User "진행해" (2026-10-26) after the gain audit: hypothesis 2, one registered run of 20 fresh models.', ...
    'decision','Codex GO 2026-10-26: R1 a2Range [0.3,1.4], paired seeds 421-425 x four methods, validation and evaluation on v5/v2.', ...
    'independentVariable',struct('field','experiment.scenario.a2Range','v5',d.v5.experiment.scenario.a2Range, ...
        'new',d.c.experiment.scenario.a2Range), ...
    'validationScenario','experiment.validationScenario = v5 experiment.scenario (validation seeds 2001-2200)', ...
    'evaluation',struct('protocol',d.v5.evaluation.protocolVersion,'cells',{d.cells}, ...
        'environmentSeeds',d.environmentSeeds,'oodA2Range',d.v5.evaluation.generalization.oodA2Range, ...
        'oodDropoutDuration',d.v5.evaluation.generalization.oodDropoutDuration, ...
        'oodNoiseScale',d.v5.evaluation.generalization.oodNoiseScale,'environment','v5 experiment'), ...
    'trainSeeds',d.trainSeeds,'methods',{d.methods},'training',d.training, ...
    'forbiddenEnvironmentSeeds',d.forbiddenEnvironmentSeeds,'criteria',d.criteria, ...
    'pairedControls',controls,'controlEvidence',evidence,'sources',code, ...
    'checkSetup',report,'notes',notes,'confirmationOpened',false,'trainingStarted',false);
fid = fopen(file,'w','n','UTF-8'); assert(fid>=0);
fwrite(fid,jsonencode(registration,'PrettyPrint',true),'char'); fclose(fid);
fprintf('[accel] registered %d sources, %d paired controls: %s\n',numel(code),numel(controls),file);
end

function p = relativePath(root,file)
p = strrep(erase(string(file),string(root)+filesep),'\','/');
end
