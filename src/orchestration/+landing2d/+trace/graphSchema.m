function S = graphSchema(agent)
% GRAPHSCHEMA  Display schema of the Actor graph stored in a checkpoint.
%   S = landing2d.trace.graphSchema(agent)
% Nodes, edges, relation types and operator classes are read from
% agent.encoderSpec (the typed topology the checkpoint stores and inference
% uses, verified by landing2d.rl.verifyCheckpointGraph at load). The Korean
% meaning table (landing2d.trace.labels) is written for tosm7_v1, so any
% change of nodes, edges, relation types, operator classes or a relation
% permutation fails here (landing2d:TraceSchema) instead of drawing stale
% arrows. The trace is defined for the canonical TOSM graph (onto_rgat_ppo),
% for the rgat_v2 encoder (two layers, one cross-relation attention pool per
% node) and the archived single-layer rgat_v1 encoders.
spec = agent.encoderSpec;
assert(isfield(spec,'mode') && strcmp(spec.mode,'context_rgat'), ...
    'landing2d:TraceSchema','The decision trace needs an R-GAT agent (context_rgat).');
schema = spec.schema; T = spec.T;
L = landing2d.trace.labels();
expectedNodes = {L.nodes.name};
expectedRelations = {L.relations.name};
expectedOperators = {'modulate','propagate','propagate','modulate','propagate'};
expectedEdges = { ...
    'VisionQuality','PadVelocity','qualifiesEstimate'; ...
    'VisionQuality','RelativePosition','qualifiesEstimate'; ...
    'VisionQuality','RelativeVelocity','qualifiesEstimate'; ...
    'PadVelocity','RelativeVelocity','informsMotion'; ...
    'RelativeVelocity','RelativePosition','informsMotion'; ...
    'DroneMotion','RelativePosition','informsMotion'; ...
    'RelativePosition','ViewMargin','affectsVisibility'; ...
    'DroneMotion','ViewMargin','affectsVisibility'; ...
    'RelativePosition','LandingCondition','conditionsLanding'; ...
    'RelativeVelocity','LandingCondition','conditionsLanding'; ...
    'DroneMotion','LandingCondition','conditionsLanding'; ...
    'ViewMargin','LandingCondition','conditionsLanding'; ...
    'VisionQuality','LandingCondition','conditionsLanding'};
fail = @(what)error('landing2d:TraceSchema', ...
    'Checkpoint graph differs from the tosm7_v1 trace schema: %s.',what);
if ~isequal(schema.nodeNames,expectedNodes), fail('node names'); end
if ~isequal(schema.relationNames,expectedRelations), fail('relation names'); end
if ~isequal(schema.relationOperators,expectedOperators), fail('relation operators'); end
if ~isequal(double(T.src),double(schema.src)) || ~isequal(double(T.dst),double(schema.dst)) ...
        || ~isequal(double(T.rel),double(schema.rel))
    fail('encoderSpec.T and encoderSpec.schema disagree');
end
N = schema.nNodes; selfId = find(strcmp(schema.relationNames,'self'));
semantic = find(T.rel ~= selfId); selfEdges = find(T.rel == selfId);
if N ~= 7 || numel(semantic) ~= 13 || numel(selfEdges) ~= 7 || schema.nRelations ~= 5 ...
        || T.nEdges ~= 20 || schema.inDim ~= 6
    fail(sprintf('counts N=%d, semantic=%d, self=%d, R=%d',N,numel(semantic), ...
        numel(selfEdges),schema.nRelations));
end
if ~isequal(double(T.src(selfEdges)),1:N) || ~isequal(double(T.dst(selfEdges)),1:N)
    fail('self edges');
end
for e = 1:13
    k = semantic(e);
    actual = {schema.nodeNames{T.src(k)},schema.nodeNames{T.dst(k)}, ...
        schema.relationNames{T.rel(k)}};
    if ~isequal(actual,expectedEdges(e,:))
        fail(sprintf('edge %d is %s -> %s (%s)',e,actual{:}));
    end
end
storedGraph = struct('perturbation','none','hash','');
if isfield(spec,'graph') && ~isempty(spec.graph), storedGraph = spec.graph; end
if ~strcmp(storedGraph.perturbation,'none') || ~isequal(double(storedGraph.rel),double(storedGraph.canonicalRel))
    fail('relation-perturbed graph (the trace explains the canonical TOSM graph only)');
end
% rgat_v2: L layers, one attention pool per destination over every incoming
% edge (no operator classes). rgat_v1: one layer, typed_v1 pools or one pool.
encoderVersion = fieldOr(spec,'encoderVersion','rgat_v1');
layers = fieldOr(spec,'layers',1);
relationOperators = 'additive_v1';
if isfield(spec,'relationOperators'), relationOperators = spec.relationOperators; end
operatorOfEdge = repmat({'propagate'},1,T.nEdges);
pool = ones(1,T.nEdges);
poolNames = {'propagate','modulate'};
if strcmp(encoderVersion,'rgat_v2')
    relationOperators = 'none';
    operatorOfEdge = repmat({'message'},1,T.nEdges);
    poolNames = {'all'};
elseif strcmp(relationOperators,'typed_v1')
    operatorOfEdge = schema.relationOperators(T.rel);
    isMod = strcmp(operatorOfEdge,'modulate');
    if ~isequal(spec.modEdges(:)',find(isMod)) || ~isequal(spec.addEdges(:)',find(~isMod))
        fail('typed_v1 operator edge split');
    end
    pool(isMod) = 2;
end
purposeKo = [L.edgePurposeKo; arrayfun(@(n)sprintf('%s 자신의 근거 유지 (자기 루프)', ...
    L.nodes(n).label),(1:N)','UniformOutput',false)];
edgeLabel = cell(1,T.nEdges);
for k = 1:T.nEdges
    edgeLabel{k} = sprintf('%s→%s',L.nodes(T.src(k)).short,L.nodes(T.dst(k)).short);
end
S = struct('version','trace_graph_schema_v1','nodeNames',{schema.nodeNames}, ...
    'nodeShort',{{L.nodes.short}},'nodeLabel',{{L.nodes.label}}, ...
    'nodePerspective',{schema.tosm.nodePerspective},'nodeClasses',{schema.nodeClasses}, ...
    'nodeFeatureNames',{schema.nodeFeatureNames},'relationNames',{schema.relationNames}, ...
    'relationOperatorNames',{schema.relationOperators},'src',double(T.src), ...
    'dst',double(T.dst),'rel',double(T.rel),'nEdges',T.nEdges,'nNodes',N, ...
    'semanticEdges',semantic,'selfEdges',selfEdges,'edgeOperator',{operatorOfEdge}, ...
    'edgePool',pool,'poolNames',{poolNames},'encoderVersion',encoderVersion,'layers',layers, ...
    'edgePurpose',{schema.edgePurpose(:)'},'edgePurposeKo',{purposeKo(:)'}, ...
    'edgeLabel',{edgeLabel},'relationOperators',relationOperators, ...
    'relationParameterSharing',fieldOr(spec,'relationParameterSharing',''), ...
    'attentionMode',spec.attentionMode,'readout',spec.readout, ...
    'hiddenDim',spec.hiddenDim,'graphDim',spec.graphDim,'inDim',spec.inDim, ...
    'residualMix',fieldOr(spec,'residualMix',0),'residualRule',fieldOr(spec,'residualRule','convex_v1'), ...
    'graphHash',storedGraph.hash,'variant',schema.variant, ...
    'tosmVersion',schema.tosm.version,'provenanceText',schema.provenance);
end

function value = fieldOr(s,name,default)
value = default;
if isfield(s,name), value = s.(name); end
end
