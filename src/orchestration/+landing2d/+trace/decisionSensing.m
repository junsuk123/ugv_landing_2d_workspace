function S = decisionSensing(env,memoryBefore,terminalEvent)
% DECISIONSENSING  Replay the environment's decision-time sensing chain, read-only.
%   S = landing2d.trace.decisionSensing(env,memoryBefore,terminalEvent)
% ENV is the environment right after reset or after a step, MEMORYBEFORE the
% common-observation memory before that capture (initialMemory at reset) and
% TERMINALEVENT whether that step ended the episode. The call sequence and
% arguments are those of landing2d.environment.reset / step (the camera frame
% and navigation fix are taken once per decision; time-indexed noise column =
% env.stepCount + 1; at reset the frame is never a dropout; a terminal step
% leaves no image). The replay then asserts that the observation and memory
% it rebuilds are identical to env.commonObservation / env.commonMemory, so
% the marker IDs, PnP outcome and KF update type it reports are those of the
% actual run (landing2d:TraceReplay otherwise). The environment itself is not
% modified or re-stepped, and the noise table is read, not drawn.
% The physical state enters only the simulated sensor models, exactly as in
% the environment; S.evaluation keeps the truth-derived flags apart.
c = env.config; e = c.experiment; co = e.commonObservation;
column = env.stepCount+1;
if env.stepCount == 0
    frameEvent = struct('dropout',false,'frameCaptured',true);
else
    frameEvent = struct('dropout',env.time>=env.sensorEvents.dropoutStart ...
        && env.time<env.sensorEvents.dropoutEnd,'frameCaptured',~terminalEvent);
end
detections = landing2d.sensing.detectMarkers(env.physicalState,env.pad,env.time, ...
    e.sensor,co,env.noise.marker(:,:,:,column),frameEvent);
navigation = landing2d.sensing.navigationEstimate(env.physicalState,env.time, ...
    co.navigation,env.noise.navigation(:,column));
[O,memory,detail] = landing2d.observation.capture(memoryBefore,detections,navigation, ...
    env.time,env.observationContext);
assert(isequaln(O,env.commonObservation) && isequaln(memory,env.commonMemory), ...
    'landing2d:TraceReplay', ['The replayed decision-time sensing at t = %.2f s ' ...
    'differs from the environment observation.'],env.time);
ugvFilter = memory.filter; previous = memoryBefore.filter;
pose = detail.pose;
attempted = detections.valid && ~isempty(detections.ids);
if ugvFilter.updated && ~previous.initialized
    kfUpdate = 'initialization';
elseif ugvFilter.updated
    kfUpdate = 'measurement_update';
elseif ugvFilter.initialized
    kfUpdate = 'time_update';
else
    kfUpdate = 'uninitialized';
end
predictionDt = NaN;
if previous.initialized, predictionDt = env.time-previous.time; end
covariance = NaN(4,1);
if ugvFilter.initialized, covariance = diag(ugvFilter.covariance); end
S = struct('time',env.time,'decisionColumn',column, ...
    'camera',struct('frameCaptured',logical(detections.valid),'stamp',detections.stamp, ...
        'markerIds',detections.ids(:)','markerCount',numel(detections.ids), ...
        'corners',detections.corners,'imageSize',detections.imageSize), ...
    'pnp',struct('attempted',attempted,'valid',logical(pose.valid), ...
        'markerCount',pose.markerCount,'reprojectionRms',pose.reprojectionRms, ...
        'translation',pose.translation,'measurement',detail.measurement, ...
        'measurementCovariance',detail.measurementCovariance), ...
    'kf',struct('initialized',ugvFilter.initialized,'update',kfUpdate, ...
        'updated',ugvFilter.updated,'lastUpdateTime',ugvFilter.lastUpdateTime, ...
        'predictionDt',predictionDt,'state',ugvFilter.state,'covarianceDiagonal',covariance), ...
    'navigation',struct('stamp',navigation.navigationStamp,'valid',logical(navigation.navigationValid), ...
        'positionXZ',navigation.positionXZ,'velocityXZ',navigation.velocityXZ, ...
        'pitchSinCos',navigation.pitchSinCos,'pitchRate',navigation.pitchRate), ...
    'observation',O, ...
    'evaluation',struct('injectedDropout',logical(frameEvent.dropout), ...
        'terminalNoImage',~frameEvent.frameCaptured));
end
