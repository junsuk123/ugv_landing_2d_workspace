function contract = validateConditionalMonteCarlo(rollouts,spec,source)
% VALIDATECONDITIONALMONTECARLO  Enforce fixed/varied variable separation.
% Every realization must be paired across methods. In sensor_noise mode the
% complete physical/exogenous case is fixed and only the three time-indexed
% measurement-noise tables vary. In policy_sampling mode those tables are
% fixed too and only a matched policy-sampling stream varies.
source = validatestring(source,{'sensor_noise','policy_sampling'});
assert(iscell(rollouts) && size(rollouts,1)>=2 && size(rollouts,2)>=2, ...
    'landing2d:MonteCarloDesignShape', ...
    'rollouts must contain at least two methods and two realizations.');
[methodCount,runCount] = size(rollouts);
reference = rollouts{1,1};
noiseSeeds = nan(methodCount,runCount,3);
noiseScales = nan(methodCount,runCount);
policySeeds = nan(methodCount,runCount);
for m = 1:methodCount
    for r = 1:runCount
        sample = rollouts{m,r};
        assert(isequaln(sample.scenario,spec.scenario), ...
            'landing2d:MonteCarloScenarioDrift', ...
            'The physical scenario changed within the conditional Monte Carlo test.');
        assert(isequaln(sample.sensorEvents,spec.sensorEvents), ...
            'landing2d:MonteCarloEventDrift', ...
            'The exogenous event schedule changed within the conditional Monte Carlo test.');
        assert(isequaln(sample.initialPhysicalState,reference.initialPhysicalState), ...
            'landing2d:MonteCarloInitialStateDrift', ...
            'The initial physical state changed within the conditional Monte Carlo test.');
        p = sample.provenance;
        noiseSeeds(m,r,:) = reshape([p.trackerNoiseSeed, ...
            p.markerNoiseSeed,p.navigationNoiseSeed],1,1,3);
        noiseScales(m,r) = p.noiseScale;
        policySeeds(m,r) = sample.policySamplingSeed;
    end
end
assert(all(noiseScales(:)==noiseScales(1,1)), ...
    'landing2d:MonteCarloNoiseScaleDrift', ...
    'The sensor-noise scale must remain fixed across methods and realizations.');
for m = 2:methodCount
    assert(isequaln(squeeze(noiseSeeds(1,:,:)),squeeze(noiseSeeds(m,:,:))), ...
        'landing2d:MonteCarloNoisePairing', ...
        'Compared methods did not receive paired measurement-noise realizations.');
end
if strcmp(source,'sensor_noise')
    uniqueNoise = unique(squeeze(noiseSeeds(1,:,:)),'rows');
    assert(size(uniqueNoise,1)==runCount,'landing2d:MonteCarloNoiseVariation', ...
        'Each sensor-noise realization must use a distinct noise-table seed triplet.');
    varied = {'tracker noise table','marker-corner noise table', ...
        'navigation noise table'};
    fixed = {'scenario and UGV trajectory','initial physical state', ...
        'dropout/pitch event schedule','dynamics and termination', ...
        'sensor-noise scale','deterministic policy weights'};
else
    referenceNoise = squeeze(noiseSeeds(1,1,:))';
    assert(all(all(squeeze(noiseSeeds(1,:,:))==referenceNoise)), ...
        'landing2d:MonteCarloNoiseDrift', ...
        'Measurement-noise tables must stay fixed in policy-sampling mode.');
    for m = 2:methodCount
        assert(isequaln(policySeeds(1,:),policySeeds(m,:)), ...
            'landing2d:MonteCarloPolicyPairing', ...
            'Compared methods did not receive paired policy-sampling streams.');
    end
    assert(numel(unique(policySeeds(1,:)))==runCount, ...
        'landing2d:MonteCarloPolicyVariation', ...
        'Every policy-sampling realization must use a distinct stream seed.');
    varied = {'matched policy-sampling stream'};
    fixed = {'scenario and UGV trajectory','initial physical state', ...
        'dropout/pitch event schedule','all measurement-noise tables', ...
        'sensor-noise scale','policy weights within each method'};
end
contract = struct('schemaVersion','conditional_mc_design_v1', ...
    'verified',true,'source',source,'pairedAcrossMethods',true, ...
    'fixedVariables',{fixed},'variedVariables',{varied}, ...
    'sensorNoiseScale',noiseScales(1,1), ...
    'measurementNoiseSeeds',squeeze(noiseSeeds(1,:,:)), ...
    'policySamplingSeeds',policySeeds(1,:), ...
    'excludedFromPrimaryClaim',strcmp(source,'policy_sampling'));
end
