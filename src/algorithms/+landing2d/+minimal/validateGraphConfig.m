function validateGraphConfig(gs)
% VALIDATEGRAPHCONFIG One explicit architecture, no configurable legacy knobs.
assert(ismember(gs.stateRepresentation,{'baseline','context_rgat'}) ...
    && strcmp(gs.readout,'relative_state') ...
    && strcmp(gs.observationSource,'commonObservation') ...
    && strcmp(gs.observationFeatures,'tosm4_v1') ...
    && ((strcmp(gs.encoderVersion,'rgat_minimal_v1') && strcmp(gs.attentionMode,'input_dependent_v1')) ...
        || (ismember(gs.encoderVersion,{'rgat_minimal_v2','rgat_minimal_v3'}) && strcmp(gs.attentionMode,'dynamic_joint_v1'))) ...
    && gs.hiddenDim==8 && gs.graphDim==8 && gs.relationDim==3 ...
    && isequal(gs.policyHiddenSizes,32) && isequal(gs.valueHiddenSizes,32), ...
    'landing2d:MinimalGraphConfig','The registered minimal architecture is fixed.');
validateattributes(gs.encoderLearnRate,{'numeric'},{'scalar','positive','finite'});
if isfield(gs,'relationPerturbation')
    p = gs.relationPerturbation;
    assert(strcmp(p.type,'edge_relation_shuffle') && p.minChangedFraction==2/3, ...
        'landing2d:MinimalShuffle','Shuffle exactly two of the three semantic labels.');
    validateattributes(p.graphSeed,{'numeric'},{'scalar','positive','integer','finite'});
end
end
