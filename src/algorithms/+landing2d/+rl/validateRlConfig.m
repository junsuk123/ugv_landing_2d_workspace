function validateRlConfig(rl)
% VALIDATERLCONFIG  Reject invalid PPO settings before training starts.
assert(strcmp(rl.trainingRegime,'direct_ppo_v1'),'landing2d:TrainingRegime', ...
    'rl.trainingRegime must be direct_ppo_v1.');
for name = {'actionInterval','hiddenSize','observationDim','actionDim','ppoIterations', ...
        'episodesPerIteration','ppoEpochs','miniBatch','evaluateEvery'}
    validateattributes(rl.(name{1}),{'numeric'}, ...
        {'scalar','real','finite','positive','integer'},mfilename,name{1});
end
for name = {'policyLearnRate','valueLearnRate','clipRatio','maxGradNorm','entropyWeight'}
    validateattributes(rl.(name{1}),{'numeric'}, ...
        {'scalar','real','finite','positive'},mfilename,name{1});
end
for name = {'seed','valueWarmup','earlyStopPatience','parallelWorkers','episodeStreamSeedOffset'}
    validateattributes(rl.(name{1}),{'numeric'}, ...
        {'scalar','real','finite','nonnegative','integer'},mfilename,name{1});
end
assert(rl.gamma>0 && rl.gamma<1 && rl.lambda>0 && rl.lambda<=1, ...
    'landing2d:Discount','gamma must lie in (0,1) and lambda in (0,1].');
assert(isfinite(rl.initialLogStd) && rl.minimumLogStd<=rl.initialLogStd, ...
    'landing2d:LogStd','minimumLogStd must not exceed initialLogStd.');
if isfield(rl,'earlyStop')
    rule = rl.earlyStop;
    assert(isstruct(rule) && strcmp(rule.rule,'validation_plateau_v1'),'landing2d:EarlyStop', ...
        'rl.earlyStop.rule must be validation_plateau_v1.');
    validateattributes(rule.window,{'numeric'},{'scalar','integer','positive'},mfilename,'earlyStop.window');
    validateattributes(rule.minimumLandingRate,{'numeric'},{'scalar','>',0,'<=',1}, ...
        mfilename,'earlyStop.minimumLandingRate');
    validateattributes(rule.minimumIterations,{'numeric'},{'scalar','integer','nonnegative'}, ...
        mfilename,'earlyStop.minimumIterations');
end
validateattributes(rl.parallelEpisodes,{'logical','numeric'},{'scalar','binary'}, ...
    mfilename,'parallelEpisodes');
assert(ischar(rl.policyFile) && ~isempty(strtrim(rl.policyFile)), ...
    'rl.policyFile must be a nonempty character vector.');
end
