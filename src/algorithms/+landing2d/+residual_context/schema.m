function [schema,T] = schema(topologyVersion)
% SCHEMA Four unchanged evidence nodes; inference context is bidirectional.
% Reverse kinematic edges inform representations, not physical causation.
% tosm4_context_accel_v1 (H3): identical nodes, edges and relations; the UGV
% acceleration estimate o11 joins TargetMotion with o4 (the target's motion).
if nargin<1, topologyVersion = 'tosm4_context_v1'; end
schema = struct('variant','tosm4_context_v1','inDim',10,'nNodes',4,'nRelations',3, ...
    'goalNode',4,'nodeNames',{{'ObservationQuality','TargetMotion','OwnMotion','RelativeState'}}, ...
    'relationNames',{{'qualifiesEstimate','informsMotion','self'}}, ...
    'relationOperators',{{'message','message','message'}}, ...
    'src',[1 2 3 1 4 4 1 2 3 4],'dst',[4 4 4 2 2 3 1 2 3 4], ...
    'rel',[1 2 2 1 2 2 3 3 3 3]);
schema.observationIndices = {[9 10],4,[3 5:8],1:2};
if strcmp(topologyVersion,'tosm4_context_accel_v1')
    schema.variant = 'tosm4_context_accel_v1'; schema.inDim = 11;
    schema.observationIndices = {[9 10],[4 11],[3 5:8],1:2};
else
    assert(strcmp(topologyVersion,'tosm4_context_v1'),'landing2d:ResidualV5Topology', ...
        'Unknown topology %s.',topologyVersion);
end
schema.edgeTable = {'ObservationQuality','RelativeState','qualifiesEstimate'; ...
    'TargetMotion','RelativeState','informsMotion'; ...
    'OwnMotion','RelativeState','informsMotion'; ...
    'ObservationQuality','TargetMotion','qualifiesEstimate'; ...
    'RelativeState','TargetMotion','informsMotion'; ...
    'RelativeState','OwnMotion','informsMotion'};
schema.edgePurpose = {'Vision freshness contextualizes relative-state estimates'; ...
    'Target motion contextualizes relative-state representation'; ...
    'Own motion contextualizes relative-state representation'; ...
    'Vision freshness contextualizes target-motion estimates'; ...
    'Relative geometry contextualizes target-motion representation'; ...
    'Relative geometry contextualizes own-motion representation'};
T = landing2d.rgat.topology(schema);
end
