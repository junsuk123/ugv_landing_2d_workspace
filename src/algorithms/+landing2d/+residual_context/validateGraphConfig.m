function validateGraphConfig(gs)
% VALIDATEGRAPHCONFIG Fixed direct-mean residual v5 architecture.
assert(strcmp(gs.encoderVersion,'relational_residual_v5') ...
    && ismember(gs.stateRepresentation,{'baseline','residual_actor'}) ...
    && ismember(gs.correctionType,{'graph','mlp'}) ...
    && strcmp(gs.observationSource,'commonObservation') ...
    && strcmp(gs.observationFeatures,'raw_residual_v1') ...
    && strcmp(gs.attentionMode,'dynamic_joint_v1') ...
    && strcmp(gs.actorMeanInitialization,'random_base_zero_correction_v1') ...
    && strcmp(gs.correctionCoordinates,'masked_own_vx_v1') ...
    && ismember(gs.topologyVersion,{'tosm4_context_v1','tosm4_context_accel_v1'}) ...
    && gs.graphDim==2 && gs.relationDim==3 && isempty(gs.policyHiddenSizes) ...
    && isequal(gs.valueHiddenSizes,55),'landing2d:ResidualV5Config','Residual v4 architecture changed.');
% Bundles: v5 (base 74, node 8, MLP correction 36 implied, all-node readout,
% beta -2), the registered C2 widths 42/12/68, or the registered C3 semantic
% operators (base 77, node 8, MLP correction 32, goal-node readout, beta 0),
% each with tanh and the v5 topology; nothing mixed.
if isfield(gs,'correctionOperators')
    assert(strcmp(gs.correctionOperators,'semantic_v1') && strcmp(gs.readout,'goal_node') ...
        && gs.basePolicyHiddenSizes==77 && gs.hiddenDim==8 && gs.correctionHiddenSize==32 ...
        && isfield(gs,'betaInit') && gs.betaInit==0 && ~isfield(gs,'correctionActivation') ...
        && strcmp(gs.topologyVersion,'tosm4_context_v1'),'landing2d:ResidualV8Bundle', ...
        'C3 must be the registered semantic-operator bundle on v5.');
elseif isfield(gs,'correctionHiddenSize')
    assert(gs.basePolicyHiddenSizes==42 && gs.hiddenDim==12 && gs.correctionHiddenSize==68 ...
        && strcmp(gs.readout,'all_nodes') && ~isfield(gs,'betaInit') ...
        && ~isfield(gs,'correctionActivation') && strcmp(gs.topologyVersion,'tosm4_context_v1'), ...
        'landing2d:ResidualV7Widths','C2 widths must be the registered 42/12/68 bundle on v5.');
else
    assert(gs.basePolicyHiddenSizes==74 && gs.hiddenDim==8 && strcmp(gs.readout,'all_nodes') ...
        && ~isfield(gs,'betaInit'),'landing2d:ResidualV5Config','Residual v4 architecture changed.');
end
validateattributes(gs.encoderLearnRate,{'numeric'},{'scalar','positive','finite'});
if isfield(gs,'correctionActivation')
    assert(ismember(gs.correctionActivation,{'tanh','soft_linear_v1'}),'landing2d:ResidualV6Activation', ...
        'Unknown correction activation %s.',gs.correctionActivation);
end
if isfield(gs,'relationPerturbation')
    p = gs.relationPerturbation;
    assert(strcmp(gs.correctionType,'graph') && strcmp(p.type,'edge_relation_shuffle') ...
        && p.minChangedFraction==2/3,'landing2d:ResidualV5Shuffle','Invalid graph perturbation.');
    validateattributes(p.graphSeed,{'numeric'},{'scalar','integer','positive','finite'});
end
end
