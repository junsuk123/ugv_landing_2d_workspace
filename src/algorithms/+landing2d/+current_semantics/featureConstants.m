function k = featureConstants(c)
% FEATURECONSTANTS Public, fixed calibration/task constants; no episode state.
% No detector noise realization, ground truth, history or action is read.
if nargin < 1
    k = struct('positionScale',3,'heightScale',8,'velocityScale',10, ...
        'verticalVelocityScale',1.5,'pitchRateScale',pi/2, ...
        'aimSlope',tan(pi/6),'approachPositionScale',3, ...
        'approachVelocityScale',1,'approachProductScale',3, ...
        'padHalfLength',.5,'touchdownSpeedX',.35,'touchdownSpeedZ',.30, ...
        'touchdownPitchTolerance',5*pi/180,'touchdownPitchRateTolerance',10*pi/180);
    return;
end
n = c.experiment.commonObservation.normalization;
s = c.experiment.safety;
positionScale = n.relativePositionScale;
velocityScale = c.experiment.reward.targetRelativeSpeed;
k = struct('positionScale',positionScale,'heightScale',n.heightScale, ...
    'velocityScale',c.vxMax,'verticalVelocityScale',c.vzMax, ...
    'pitchRateScale',c.experiment.dynamics.pitchRateLimit, ...
    'aimSlope',tan(-c.experiment.sensor.cameraPitchOffset), ...
    'approachPositionScale',positionScale,'approachVelocityScale',velocityScale, ...
    'approachProductScale',positionScale*velocityScale, ...
    'padHalfLength',c.padHalfLength,'touchdownSpeedX',s.touchdownSpeedX, ...
    'touchdownSpeedZ',s.touchdownSpeedZ,'touchdownPitchTolerance',s.touchdownPitchTolerance, ...
    'touchdownPitchRateTolerance',s.touchdownPitchRateTolerance);
end
