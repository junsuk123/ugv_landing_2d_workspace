function validateGraphConfig(gs)
% VALIDATEGRAPHCONFIG Registered current-only encoder and four-arm contract.
required = {'encoderVersion','encoderMode','stateRepresentation','hiddenDim','layers', ...
    'policyHiddenSizes','valueHiddenSizes','encoderLearnRate','featureConstants', ...
    'readout','observationSource','observationFeatures'};
assert(isstruct(gs) && isscalar(gs) && all(isfield(gs,required)), ...
    'landing2d:CurrentSemanticsConfig','Missing current-semantics configuration fields.');
assert(strcmp(gs.encoderVersion,'current_semantics_v1'), ...
    'landing2d:CurrentSemanticsVersion','Use current_semantics_v1.');
modes = {'baseline','semantic_mlp','untyped','rgat'};
assert(ismember(gs.encoderMode,modes),'landing2d:CurrentSemanticsMode', ...
    'Use baseline, semantic_mlp, untyped or rgat.');
widths = [110 65 55 46];
index = find(strcmp(modes,gs.encoderMode),1);
assert(isscalar(gs.policyHiddenSizes) && gs.policyHiddenSizes==widths(index) ...
    && isequal(gs.valueHiddenSizes,55) && isequal(gs.hiddenDim,8) && isequal(gs.layers,2), ...
    'landing2d:CurrentSemanticsBudget','The registered widths or two-hop contract changed.');
representation = 'current_semantics_actor';
if strcmp(gs.encoderMode,'baseline'), representation = 'baseline'; end
assert(strcmp(gs.stateRepresentation,representation), ...
    'landing2d:CurrentSemanticsRepresentation','Mode and representation disagree.');
assert(strcmp(gs.readout,'raw_goal_concat') && strcmp(gs.observationSource,'commonObservation') ...
    && strcmp(gs.observationFeatures,'raw_current_v1'), ...
    'landing2d:CurrentSemanticsInput','The current-only raw-input/readout contract changed.');
validateattributes(gs.encoderLearnRate,{'numeric'},{'scalar','real','positive','finite'});
assert(~isfield(gs,'relationPerturbation'),'landing2d:CurrentSemanticsAblation', ...
    'This four-arm experiment uses an untyped control, not a relation shuffle.');
if isfield(gs,'featureSchema')
    assert(strcmp(gs.featureSchema,'current_semantics_v1'),'landing2d:CurrentSemanticsFeatures', ...
        'Unknown feature schema.');
end
if isfield(gs,'featureMode')
    assert(strcmp(gs.featureMode,'raw_current_v1'),'landing2d:CurrentSemanticsFeatures', ...
        'Only current observations may enter the feature generator.');
end
% Validate constants through a valid synthetic CURRENT observation only.
landing2d.current_semantics.features([.1;.2;.02;.1;-.02;0;1;0;1;0],gs.featureConstants);
end
