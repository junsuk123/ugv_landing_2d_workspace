function validateGraphConfig(gs)
% VALIDATEGRAPHCONFIG Fixed stage-1 architecture, not a parameter search.
assert(strcmp(gs.encoderVersion,'relational_residual_v1') ...
    && ismember(gs.stateRepresentation,{'baseline','residual_actor'}) ...
    && ismember(gs.correctionType,{'graph','mlp'}) ...
    && strcmp(gs.observationSource,'commonObservation') ...
    && strcmp(gs.observationFeatures,'raw_residual_v1') ...
    && strcmp(gs.readout,'all_nodes') && strcmp(gs.attentionMode,'dynamic_joint_v1') ...
    && gs.hiddenDim==8 && gs.graphDim==16 && gs.relationDim==3 ...
    && isequal(gs.policyHiddenSizes,16) && isequal(gs.valueHiddenSizes,55), ...
    'landing2d:ResidualConfig','The registered residual architecture is fixed.');
validateattributes(gs.encoderLearnRate,{'numeric'},{'scalar','positive','finite'});
if isfield(gs,'relationPerturbation')
    p = gs.relationPerturbation;
    assert(strcmp(gs.correctionType,'graph') && strcmp(p.type,'edge_relation_shuffle') ...
        && p.minChangedFraction==2/3,'landing2d:ResidualShuffle','Invalid graph perturbation.');
    validateattributes(p.graphSeed,{'numeric'},{'scalar','integer','positive','finite'});
end
end
