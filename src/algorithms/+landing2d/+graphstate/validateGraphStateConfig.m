function validateGraphStateConfig(gs)
% VALIDATEGRAPHSTATECONFIG  State-representation settings of the planar contract.
assert(ischar(gs.stateRepresentation) && ismember(gs.stateRepresentation, ...
    {'baseline','context_rgat'}),'landing2d:UnknownStateRepresentation', ...
    'graphState.stateRepresentation must be baseline or context_rgat.');
assert(strcmp(gs.readout,'grouped_factorized'),'landing2d:UnknownReadout', ...
    'graphState.readout must be grouped_factorized.');
assert(ismember(gs.attentionMode,{'input_dependent_v1','fixed_relation_v1'}), ...
    'landing2d:RgatAttentionMode', ...
    'graphState.attentionMode must be input_dependent_v1 or fixed_relation_v1.');
assert(strcmp(gs.observationSource,'commonObservation') ...
    && strcmp(gs.observationFeatures,'tosm7_v1'),'landing2d:GraphObservationFeatures', ...
    'The graph is the tosm7_v1 graph of the common observation.');
for name = {'hiddenDim','relationDim','graphDim'}
    validateattributes(gs.(name{1}),{'numeric'}, ...
        {'scalar','real','finite','positive','integer'},mfilename,name{1});
end
for name = {'policyHiddenSizes','valueHiddenSizes'}
    validateattributes(gs.(name{1}),{'numeric'}, ...
        {'vector','numel',2,'real','finite','positive','integer'},mfilename,name{1});
end
for name = {'initScale','encoderLearnRate'}
    validateattributes(gs.(name{1}),{'numeric'}, ...
        {'scalar','real','finite','positive'},mfilename,name{1});
end
% Only the shuffled comparison arm carries a relation permutation.
if isfield(gs,'relationPerturbation')
    p = gs.relationPerturbation;
    assert(isstruct(p) && isscalar(p) && strcmp(p.type,'edge_relation_shuffle') ...
        && strcmp(gs.stateRepresentation,'context_rgat'),'landing2d:RelationPerturbation', ...
        'graphState.relationPerturbation must be an edge_relation_shuffle of context_rgat.');
    validateattributes(p.graphSeed,{'numeric'},{'scalar','integer','positive'}, ...
        mfilename,'relationPerturbation.graphSeed');
end
assert(ischar(gs.policyFile) && ~isempty(strtrim(gs.policyFile)), ...
    'graphState.policyFile must be a nonempty character vector.');
end
