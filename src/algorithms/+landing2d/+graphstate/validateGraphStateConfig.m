function validateGraphStateConfig(gs)
% VALIDATEGRAPHSTATECONFIG  State-representation settings of the planar contract.
assert(ischar(gs.stateRepresentation) && ismember(gs.stateRepresentation, ...
    {'baseline','context_rgat'}),'landing2d:UnknownStateRepresentation', ...
    'graphState.stateRepresentation must be baseline or context_rgat.');
assert(strcmp(gs.readout,'grouped_factorized'),'landing2d:UnknownReadout', ...
    'graphState.readout must be grouped_factorized.');
assert(ismember(gs.attentionMode,{'input_dependent_v1','fixed_relation_v1'}), ...
    'landing2d:RgatAttentionMode', ...
    'graphState.attentionMode must be input_dependent_v1 or fixed_relation_v1.');
assert(strcmp(gs.observationSource,'commonObservation') ...
    && strcmp(gs.observationFeatures,'tosm7_v2'),'landing2d:GraphObservationFeatures', ...
    'The graph is the tosm7_v2 graph of the common observation.');
for name = {'hiddenDim','relationDim','graphDim'}
    validateattributes(gs.(name{1}),{'numeric'}, ...
        {'scalar','real','finite','positive','integer'},mfilename,name{1});
end
for name = {'policyHiddenSizes','valueHiddenSizes', ...
        'operatorSharedPolicyHiddenSizes','operatorSharedValueHiddenSizes'}
    validateattributes(gs.(name{1}),{'numeric'}, ...
        {'vector','numel',2,'real','finite','positive','integer'},mfilename,name{1});
end
for name = {'initScale','encoderLearnRate'}
    validateattributes(gs.(name{1}),{'numeric'}, ...
        {'scalar','real','finite','positive'},mfilename,name{1});
end
assert(isfield(gs,'encoderVersion') && ismember(gs.encoderVersion,{'rgat_v1','rgat_v2'}), ...
    'landing2d:EncoderVersion','graphState.encoderVersion must be rgat_v1 or rgat_v2.');
if strcmp(gs.encoderVersion,'rgat_v2')
    assert(~isfield(gs,'relationOperators') && ~isfield(gs,'relationParameterSharing'), ...
        'landing2d:EncoderVersion', ['rgat_v2 has no relation operator classes ' ...
        '(relationOperators / relationParameterSharing belong to rgat_v1).']);
    for name = {'layers','relationBases'}
        validateattributes(gs.(name{1}),{'numeric'}, ...
            {'scalar','real','finite','positive','integer'},mfilename,name{1});
    end
    for name = {'v2PolicyHiddenSizes','v2ValueHiddenSizes'}
        validateattributes(gs.(name{1}),{'numeric'}, ...
            {'vector','numel',2,'real','finite','positive','integer'},mfilename,name{1});
    end
    if isfield(gs,'v2HiddenDim')
        validateattributes(gs.v2HiddenDim,{'numeric'}, ...
            {'scalar','real','finite','positive','integer'},mfilename,'v2HiddenDim');
    end
    % Fixed (untrained) residual interpolation of layers 2..L, 0 = none.
    if isfield(gs,'residualMix')
        validateattributes(gs.residualMix,{'numeric'},{'scalar','real','>=',0,'<=',1}, ...
            mfilename,'residualMix');
    end
    if isfield(gs,'residualRule')
        assert(ismember(gs.residualRule,{'convex_v1','variance_preserving_v1'}), ...
            'landing2d:ResidualRule','graphState.residualRule must be convex_v1 or variance_preserving_v1.');
    end
    if isfield(gs,'v2InitGain')
        validateattributes(gs.v2InitGain,{'numeric'},{'scalar','real','finite','positive'}, ...
            mfilename,'v2InitGain');
    end
    % relational-policy-v2.4: relation operators fixed by the ontology meaning.
    if isfield(gs,'v2Operators')
        assert(ismember(gs.v2Operators,{'none','semantic_fixed_v1','semantic_bottleneck_v1', ...
            'semantic_reliability_bottleneck_v1'}), ...
            'landing2d:V2Operators', ['graphState.v2Operators must be none, ' ...
            'semantic_fixed_v1, semantic_bottleneck_v1 or ' ...
            'semantic_reliability_bottleneck_v1.']);
    end
    if isfield(gs,'v2RelationParameterization')
        assert(ismember(gs.v2RelationParameterization, ...
            {'trainable_basis_v1','fixed_cyclic_codebook_v1', ...
            'fixed_semantic_codebook_v1'}), ...
            'landing2d:RelationParameterization', ...
            'Unknown rgat_v2 relation parameterization.');
        if ismember(gs.v2RelationParameterization, ...
                {'fixed_cyclic_codebook_v1','fixed_semantic_codebook_v1'})
            assert(strcmp(gs.v2Operators,'none') && gs.relationBases==3 ...
                && gs.relationDim==4,'landing2d:RelationParameterization', ...
                'A fixed relation codebook requires no operators, 3 bases and relationDim 4.');
        end
    end
end
if isfield(gs,'relationOperators')
    assert(strcmp(gs.stateRepresentation,'context_rgat') ...
        && ismember(gs.relationOperators,{'additive_v1','typed_v1'}), ...
        'landing2d:RelationOperators', ...
        'graphState.relationOperators (context_rgat only) must be additive_v1 or typed_v1.');
end
if isfield(gs,'relationParameterSharing')
    assert(strcmp(gs.stateRepresentation,'context_rgat') ...
        && strcmp(gs.relationOperators,'typed_v1') ...
        && strcmp(gs.relationParameterSharing,'operator_shared_v1'), ...
        'landing2d:RelationParameterSharing', ...
        'operator_shared_v1 is supported only by context_rgat typed_v1.');
end
% Only the shuffled comparison arm carries a relation permutation.
if isfield(gs,'relationPerturbation')
    p = gs.relationPerturbation;
    assert(isstruct(p) && isscalar(p) && strcmp(p.type,'edge_relation_shuffle') ...
        && strcmp(gs.stateRepresentation,'context_rgat'),'landing2d:RelationPerturbation', ...
        'graphState.relationPerturbation must be an edge_relation_shuffle of context_rgat.');
    validateattributes(p.graphSeed,{'numeric'},{'scalar','integer','positive'}, ...
        mfilename,'relationPerturbation.graphSeed');
    if isfield(p,'minChangedFraction')
        validateattributes(p.minChangedFraction,{'numeric'},{'scalar','>=',0,'<=',1}, ...
            mfilename,'relationPerturbation.minChangedFraction');
    end
    if isfield(p,'minOperatorChangedFraction')
        validateattributes(p.minOperatorChangedFraction,{'numeric'}, ...
            {'scalar','>=',0,'<=',1},mfilename, ...
            'relationPerturbation.minOperatorChangedFraction');
    end
end
assert(ischar(gs.policyFile) && ~isempty(strtrim(gs.policyFile)), ...
    'graphState.policyFile must be a nonempty character vector.');
end
