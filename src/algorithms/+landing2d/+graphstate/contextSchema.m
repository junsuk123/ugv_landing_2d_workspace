function [schema,T] = contextSchema(mode,~,~,features)
% CONTEXTSCHEMA  Reduced TOSM ontology graph of the planar study (tosm7_v5).
%   [schema,T] = landing2d.graphstate.contextSchema('context_rgat')
%   [schema,T] = landing2d.graphstate.contextSchema('context_rgat',[],[],'tosm7_v2')
% 7 nodes, 4 semantic relations + self (13 semantic + 7 self edges), 6 node
% channels (5 node-specific features + typeId) computed from the registered
% 10-D o_t (landing2d.graphstate.observationVectorGraph); see
% docs/TOSM7_ONTOLOGY_KO.md. The second and third arguments are accepted for
% call compatibility (2-D, common observation only). FEATURES (default
% tosm7_v5) changes only the descriptive feature labels of LandingCondition;
% topology and every structural field are the same for every version.
if nargin < 1 || isempty(mode), mode = 'context_rgat'; end
if nargin < 4 || isempty(features), features = 'tosm7_v5'; end
assert(ismember(features,{'tosm7_v2','tosm7_v3','tosm7_v4','tosm7_v5'}),'landing2d:GraphObservationFeatures', ...
    'Only the tosm7_v2/v3/v4/v5 graphs are supported.');
[schema,T] = tosmReducedSchema(mode,features);
end

function [schema,T] = tosmReducedSchema(mode,features)
% Reduced TOSM ontology of the planar study (docs/TOSM7_ONTOLOGY_KO.md).
% Research scope: incomplete visual observation (qualifiesEstimate), UGV
% motion change (informsMotion) and the basic visibility/touchdown condition
% (affectsVisibility, conditionsLanding). Independent estimation/control
% delay and 3-D contact safety are deliberately out of scope.
%   N1-N5 Explicit: deterministic transforms of the registered 10-D o_t.
%   N6-N7 Implicit: ViewMargin, computed from the same o_t and the public
%         camera constants (no new sensor, estimator, covariance or
%         innovation), and LandingCondition: the signed o_t entries of the
%         five touchdown quantities in tosm7_v4, latent in tosm7_v3 (typeId
%         only) and the touchdown-limit ratios in tosm7_v2. In tosm7_v5 only
%         LandingCondition's duplicate drone_vz is zero. Neither is a guard: no
%         action, approval, reward or termination depends on them.
% The relation structure is fixed; only node features change every step.
assert(strcmp(mode,'context_rgat'),'landing2d:ContextMode', ...
    'Unknown TOSM observation graph mode %s.',mode);
schema.nodeNames = {'VisionQuality','PadVelocity','RelativePosition', ...
    'RelativeVelocity','DroneMotion','ViewMargin','LandingCondition'};
schema.nNodes = numel(schema.nodeNames);
schema.ontologyNodes = 1:schema.nNodes;
schema.nodeClasses = {'ObservationQuality','TargetMotion','RelativeState', ...
    'RelativeState','OwnMotion','VisibilityContext','LandingContext'};
schema.relationNames = {'qualifiesEstimate','informsMotion', ...
    'affectsVisibility','conditionsLanding','self'};
% Operator class of each relation type (graphState.relationOperators =
% 'typed_v1', landing2d.graphstate.encoderForward), read from the relation
% meaning:
%   modulate   "A qualifies / conditions B": A changes how much B's own
%              evidence counts -> multiplicative gate on B's node state
%   propagate  "A informs / affects B" (and self): A adds to B's state
%              -> additive message
% The class belongs to the relation type, so the shuffled control applies the
% same operators to the edges that carry those labels after the permutation.
schema.relationOperators = {'modulate','propagate','propagate','modulate','propagate'};
edges = { ...
    'VisionQuality','PadVelocity','qualifiesEstimate'; ...
    'VisionQuality','RelativePosition','qualifiesEstimate'; ...
    'VisionQuality','RelativeVelocity','qualifiesEstimate'; ...
    'PadVelocity','RelativeVelocity','informsMotion'; ...
    'RelativeVelocity','RelativePosition','informsMotion'; ...
    'DroneMotion','RelativePosition','informsMotion'; ...
    'RelativePosition','ViewMargin','affectsVisibility'; ...
    'DroneMotion','ViewMargin','affectsVisibility'; ...
    'RelativePosition','LandingCondition','conditionsLanding'; ...
    'RelativeVelocity','LandingCondition','conditionsLanding'; ...
    'DroneMotion','LandingCondition','conditionsLanding'; ...
    'ViewMargin','LandingCondition','conditionsLanding'; ...
    'VisionQuality','LandingCondition','conditionsLanding'};
purposes = { ...
    'marker update/age qualifies the UGV velocity estimate'; ...
    'marker update/age qualifies the relative position estimate'; ...
    'marker update/age qualifies the relative velocity estimate'; ...
    'UGV velocity change drives the relative horizontal velocity'; ...
    'relative velocity changes the relative horizontal position over time'; ...
    'drone vertical motion changes the relative height over time'; ...
    'relative placement sets the marker bearing in the camera'; ...
    'pitch rotates the body-fixed camera and its field of view'; ...
    'horizontal offset conditions the touchdown footprint'; ...
    'relative horizontal speed conditions touchdown'; ...
    'descent speed and attitude condition touchdown'; ...
    'remaining view margin conditions a reliable final descent'; ...
    'marker recency conditions how far the estimates can be trusted'};
src=zeros(1,size(edges,1)); dst=src; rel=src;
for i=1:size(edges,1)
    src(i)=find(strcmp(schema.nodeNames,edges{i,1}));
    dst(i)=find(strcmp(schema.nodeNames,edges{i,2}));
    rel(i)=find(strcmp(schema.relationNames,edges{i,3}));
end
self=find(strcmp(schema.relationNames,'self'));
src=[src,1:schema.nNodes]; dst=[dst,1:schema.nNodes];
rel=[rel,self*ones(1,schema.nNodes)];
purposes=[purposes;arrayfun(@(n)sprintf('%s local evidence is retained', ...
    schema.nodeNames{n}),1:schema.nNodes,'UniformOutput',false)'];
schema.nRelations=numel(schema.relationNames);
schema.src=src; schema.dst=dst; schema.rel=rel;
% Six channels: five node-specific features plus the node identity code.
% nodeFeatureNames lists the meaning of f1..f5 for every node (descriptive
% labels; no computation, hash or signature reads them). tosm7_v2 dropped
% N3 normalizedCrossTrack / geometryQuadratic (normalized-axis cross-track,
% not the metric aim error) and N5 navigationValid / navigationAge (constant);
% their channels are zero padding. N6:
% normalizedBearing is bearing/(FOV/2); N7 (tosm7_v2 only): bounded* are
% r/(1+r) of the touchdown-limit ratios r
% (landing2d.graphstate.observationVectorGraph); in tosm7_v3 the five N7
% channels are zero; in tosm7_v4 they are the signed o_t entries relative_x,
% relative_vx, drone_vz, drone_sinTheta, drone_pitchRate. typeId is the node
% identity code node/N (one value per node, not the nodeClasses entry).
schema.featureNames={'f1','f2','f3','f4','f5','typeId'};
schema.inDim=numel(schema.featureNames);
schema.observationFeatures=features;
schema.nodeFeatureNames={ ...
    'visionUpdated','visionAge','','','',''; ...
    'ugv_vx','ugv_vx^2','','','',''; ...
    'relative_x','relative_height','','','',''; ...
    'relative_vx','relative_vx^2','','','',''; ...
    'drone_vz','drone_sinTheta','drone_pitchRate','','',''; ...
    'fovMargin','normalizedBearing','','','',''; ...
    'boundedPositionRatio','boundedRelativeSpeedRatio','boundedDescentSpeedRatio', ...
    'boundedPitchRatio','boundedPitchRateRatio',''};
if strcmp(features,'tosm7_v3'), schema.nodeFeatureNames(7,1:5)={''}; end
if ismember(features,{'tosm7_v4','tosm7_v5'})
    schema.nodeFeatureNames(7,1:5)={'relative_x','relative_vx','drone_vz', ...
        'drone_sinTheta','drone_pitchRate'};
    if strcmp(features,'tosm7_v5'), schema.nodeFeatureNames{7,3}=''; end
end
schema.nodeFeatureNames(:,end)={'typeId'};
schema.neutralValue=zeros(1,schema.nNodes);
% The LandingCondition node (descriptive situation feature, never a guard,
% risk prediction or approval).
schema.landingConditionNodes=find(strcmp(schema.nodeNames,'LandingCondition'));
% goalNode: legacy alias copied into the topology (and so into every saved
% checkpoint); nothing reads it.
schema.goalNode=schema.landingConditionNodes;
schema.actionNodes=[];
% Identity readout keeps every node identifiable (no raw observation bypass).
schema.groupNames=schema.nodeNames;
schema.readoutGroups=num2cell(1:schema.nNodes);
schema.groupMatrix=eye(schema.nNodes);
% Deterministic start of the factorized readout: row k of [node,channel]
% starts as one explicit ontology coordinate. Wc/Wn remain trainable
% (landing2d.graphstate.encoderInit).
schema.readoutInit=[1,1;1,2;2,1;3,1;3,2;3,3;4,1;5,1;5,2;5,3;5,4;5,5; ...
    6,1;6,2;7,1;7,3];
schema.variant='tosm7_rgat_v2';
schema.observationSource='commonObservation';
schema.knowledgeModel='TOSM';
schema.tosm=tosmReducedMetadata(schema.nodeNames);
schema.edgeTable=edges;
schema.edgePurpose=purposes;
schema.provenance=struct( ...
    'VisionQuality','ugv_visionUpdated, ugv_visionAge', ...
    'PadVelocity','ugv_vx (marker/KF estimate)', ...
    'RelativePosition','relative_x, relative_height', ...
    'RelativeVelocity','relative_vx', ...
    'DroneMotion','drone_vz, drone_sinTheta, drone_pitchRate (own navigation estimate)', ...
    'ViewMargin',['predicted FOV/2-|bearing| from relative_x, relative_height, ' ...
        'pitch and the camera mounting; an estimate, not a detection'], ...
    'LandingCondition',['|e_x|, |v_r|, |v_z|, |theta|, |theta_dot| against ' ...
        'the mechanical touchdown limits; current-state suitability, never a guard']);
if strcmp(features,'tosm7_v3')
    schema.provenance.LandingCondition=['latent: no node features (typeId only); ' ...
        'state formed by the conditionsLanding messages, never a guard'];
elseif strcmp(features,'tosm7_v5')
    schema.provenance.LandingCondition=['relative_x, relative_vx, zero, ' ...
        'drone_sinTheta, drone_pitchRate (signed o_t entries; drone_vz is ' ...
        'present only in DroneMotion and reaches the sink through messages); never a guard'];
elseif strcmp(features,'tosm7_v4')
    schema.provenance.LandingCondition=['relative_x, relative_vx, drone_vz, ' ...
        'drone_sinTheta, drone_pitchRate (signed o_t entries of the touchdown ' ...
        'quantities); current-state context, never a guard'];
end
if nargout>1, T=landing2d.rgat.topology(schema); end
end

function M=tosmReducedMetadata(nodeNames)
% Descriptive TOSM views; excluded from node features and topology.
M=struct();
M.version='tosm_landing_v2_reduced';
M.perspectives={'Symbolic','Explicit','Implicit'};
M.symbolicHierarchy=struct( ...
    'root','LandingDomainEntity', ...
    'classes',{{'PhysicalEntity','Observation','EstimatedState','ControlContext'}}, ...
    'physicalEntities',{{'UAV','UGV','LandingPad'}}, ...
    'observations',{{'VisualObservation'}}, ...
    'estimatedStates',{{'PadVelocity','RelativePosition','RelativeVelocity','DroneMotion'}}, ...
    'controlContexts',{{'ViewMargin','LandingCondition'}});
M.nodePerspective={'Explicit','Explicit','Explicit','Explicit','Explicit', ...
    'Implicit','Implicit'};
M.nodeRole={'ObservationQuality','EstimatedState','EstimatedState', ...
    'EstimatedState','EstimatedState','ControlContext','ControlContext'};
M.removedConcepts={ ...
    'NavigationObservation','no navigation-fault scenario; the always-valid fix has no validity/age input'; ...
    'TemporalContext','estimation/control delay is not studied in the 2D model'; ...
    'ActuationState','no actuator-delay study'; ...
    'ObservationReliability','merged into VisionQuality (no covariance/innovation in o_t)'; ...
    'MotionConsistency','would need innovation/NIS, i.e. a new observation contract'; ...
    'TrackingDemand','left to R-GAT/PPO from relative position/velocity'; ...
    'DescentReadiness','merged into LandingCondition'};
% Relations the controlled evaluation exercises (relational_policy_v1):
% marker dropout (qualifiesEstimate), UGV acceleration (informsMotion) and
% their combination; the landing condition is measured in every case.
M.evaluatedRelations={ ...
    'qualifiesEstimate','marker dropout (S2, S4; update probe)'; ...
    'informsMotion','UGV acceleration (S3, S4; velocity probe)'; ...
    'affectsVisibility,conditionsLanding','approach view loss, unsuitable descent'};
M.interpretation=['Symbolic concepts define meaning; Explicit nodes are ' ...
    'deterministic functions of the registered 12-D observation; Implicit ' ...
    'nodes are situation features computed from the same observation. No ' ...
    'TOSM item is a hard action, landing-approval, supervisor or termination rule.'];
assert(numel(nodeNames)==numel(M.nodePerspective) ...
    && numel(nodeNames)==numel(M.nodeRole), ...
    'landing2d:TosmMetadata','TOSM metadata must cover every graph node.');
end
